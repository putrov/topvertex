#!/usr/bin/env python
r"""Generate the LaTeX fragments in notes/generated/ that notes/topvertex_notes.tex \input's.

Run from the repository root (or anywhere) with the project venv:

    .venv/bin/python notes/make_tables.py

Every number in the fragments is computed by the package ``topvertex`` (conventions of
Konishi, math/0504188, as fixed in CONVENTIONS.md), except gv_tables.tex, which typesets the
literature oracle tables of tests/data.py (KKV hep-th/9910181 for local P^2, CKYZ hep-th/9903053
for local F0).  Files written:

    vertex_table.tex   C_{l1 l2 l3}(q) for |l1|+|l2|+|l3| <= 3, one row per cyclic orbit
    conifold_terms.tex Z_1, Z_2, Z_3 and F_1, F_2, F_3 of the resolved conifold
    p2_terms.tex       Z_1, Z_2, Z_3 of local P^2, F_d, f_d, y f_d and the GV numbers
    f0_terms.tex       Z_beta of local P^1 x P^1 for total degree <= 2, and GV numbers
    gv_tables.tex      the oracle GV tables (local P^2: n^g_d, d <= 5; local F0: n^0, d_B, d_F <= 3)

Rational functions are printed from the reduced representation of
:class:`topvertex.qring.QFrac` (``QFrac.cancel()``): numerator a Laurent polynomial in
q^{1/2}, denominator a product of q-numbers [k] = q^{k/2} - q^{-k/2}.  (This is the content
of ``QFrac.latex()``, typeset with negative powers q^{-k} instead of 1/q^k.)  When the
numerator is invariant under q -> 1/q and has integral q-powers it is also given as a
polynomial in y = [1]^2 = q - 2 + q^{-1} (``QFrac.to_y_polynomial``).

Package entry points used: topvertex.vertex.vertex, topvertex.examples_geometry.{conifold,
local_p2, local_f0}, topvertex.partition_function.{partition_function, gv_invariants},
Series.substitute / Series.log.  The script also asserts that the package reproduces the
numbers computed BY HAND in the notes (Sections 5, 7, 8), so a convention change in the package
that would make the text inconsistent makes this script fail.
"""
from __future__ import annotations

import sys
from fractions import Fraction
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
OUT = HERE / "generated"
sys.path.insert(0, str(ROOT))

from topvertex.qring import QFrac  # noqa: E402
from topvertex.partitions import partitions_of, conjugate  # noqa: E402
from topvertex.vertex import vertex  # noqa: E402

HEADER = "% GENERATED by notes/make_tables.py from the topvertex package -- do not edit by hand.\n"


# ----------------------------------------------------------------------------- formatting

def _qpow(n: int) -> str:
    """LaTeX for q^{n/2} (n = exponent of x = q^{1/2})."""
    if n == 0:
        return ""
    if n % 2 == 0:
        e = n // 2
        return "q" if e == 1 else f"q^{{{e}}}"
    return f"q^{{{n}/2}}"


def _coef_term(c: Fraction, mono: str, first: bool) -> str:
    sign = "-" if c < 0 else "+"
    a = abs(c)
    if mono:
        body = (mono if a == 1 else f"{_frac(a)}{mono}")
    else:
        body = _frac(a)
    if first:
        return ("-" if c < 0 else "") + body
    return f" {sign} {body}"


def _frac(a: Fraction) -> str:
    a = Fraction(a)
    return str(a.numerator) if a.denominator == 1 else rf"\tfrac{{{a.numerator}}}{{{a.denominator}}}"


def laurent_latex(coeffs: dict[int, Fraction], group_symmetric: bool = True) -> str:
    """LaTeX of sum_n c_n x^n (x = q^{1/2}), highest power first.  If the polynomial is
    invariant under x -> 1/x, write it as c_0 + sum_{n>0} c_n (q^{n/2} + q^{-n/2})."""
    coeffs = {n: Fraction(c) for n, c in coeffs.items() if c}
    if not coeffs:
        return "0"
    sym = group_symmetric and all(coeffs.get(-n, 0) == c for n, c in coeffs.items()) and len(coeffs) > 1
    out = []
    if sym:
        for n in sorted((n for n in coeffs if n > 0), reverse=True):
            c = coeffs[n]
            mono = f"{_qpow(n)}+{_qpow(-n)}" if c == 1 else f"({_qpow(n)}+{_qpow(-n)})"
            out.append(_coef_term(c, mono, not out))
        if 0 in coeffs:
            out.append(_coef_term(coeffs[0], "", not out))
    else:
        for n in sorted(coeffs, reverse=True):
            out.append(_coef_term(coeffs[n], _qpow(n), not out))
    return "".join(out)


def den_latex(den: dict[int, int]) -> str:
    return "".join(f"[{k}]" + (f"^{{{m}}}" if m > 1 else "") for k, m in sorted(den.items()))


def _normalise(coeffs: dict[int, Fraction]) -> tuple[int, int, dict[int, Fraction]]:
    """Write sum c_n x^n = (sign / m) * sum c'_n x^n with integer c'_n (m >= 1) and, if all c_n
    are negative, sign = -1 and c'_n > 0.  Returns (sign, m, c')."""
    from math import lcm
    coeffs = {n: Fraction(c) for n, c in coeffs.items() if c}
    m = 1
    for c in coeffs.values():
        m = lcm(m, c.denominator)
    sign = -1 if coeffs and all(c < 0 for c in coeffs.values()) else 1
    return sign, m, {n: c * m * sign for n, c in coeffs.items()}


def _assemble(sign: int, m: int, num: str, den: str) -> str:
    s = "-" if sign < 0 else ""
    if m > 1:
        den = f"{m}{den}" if den else str(m)
    if not den:
        return s + (f"({num})" if s and (" + " in num or " - " in num) else num)
    return rf"{s}\frac{{{num}}}{{{den}}}"


def qfrac_latex(f: QFrac, group_symmetric: bool = True) -> str:
    """Reduced form  numerator / prod [k]^m  of a QFrac (overall sign and rational content
    pulled out)."""
    f = f.cancel()
    sign, m, c = _normalise(f.numerator_laurent())
    return _assemble(sign, m, laurent_latex(c, group_symmetric), den_latex(f.denominator))


def y_poly_latex(cs) -> str:
    """LaTeX of sum_g c_g y^g, highest power first."""
    out = []
    for g in range(len(cs) - 1, -1, -1):
        c = cs[g]
        if c == 0:
            continue
        mono = "" if g == 0 else ("y" if g == 1 else f"y^{{{g}}}")
        out.append(_coef_term(Fraction(c), mono, not out))
    return "".join(out) if out else "0"


def y_form(f: QFrac) -> str | None:
    """f = P(y) / prod [k]^m with P a polynomial in y, if the numerator allows it."""
    f = f.cancel()
    sign, m, c = _normalise(f.numerator_laurent())
    try:
        cs = QFrac.from_laurent(c).to_y_polynomial()
    except ValueError:
        return None
    return _assemble(sign, m, y_poly_latex(cs), den_latex(f.denominator))


def part_latex(lam) -> str:
    if not lam:
        return r"\es"
    return "(" + ",".join(map(str, lam)) + ")"


def write(name: str, text: str, placeholder: bool = False):
    OUT.mkdir(exist_ok=True)
    head = HEADER
    if placeholder:
        head = "% PLACEHOLDER -- regenerate with make_tables.py\n"
    (OUT / name).write_text(head + text)
    print(f"wrote {OUT / name}")


# ----------------------------------------------------------------------------- hand values

def _y() -> QFrac:
    return QFrac.qnum(1) ** 2


def _ypoly(cs) -> QFrac:
    y, out = _y(), QFrac.zero()
    for g, c in enumerate(cs):
        out = out + y ** g * c
    return out


def check_hand_values():
    """Assert the by-hand formulas of the notes against the package."""
    q1, q2, q3, y = QFrac.qnum(1), QFrac.qnum(2), QFrac.qnum(3), _y()
    xq = QFrac.x_pow
    # Section 5: vertex values
    assert vertex((1,), (), ()) == 1 / q1
    assert vertex((2,), (), ()) == xq(1) / (q1 * q2)
    assert vertex((1, 1), (), ()) == xq(-1) / (q1 * q2)
    assert vertex((1,), (1,), ()) == (y + 1) / y == vertex((1,), (), (1,))
    assert vertex((1,), (1,), (1,)) == _ypoly([1, 3, 1]) / q1 ** 3
    assert vertex((2,), (1,), ()) == (xq(2) + xq(1) / (q1 * q2)) / q1
    assert vertex((2,), (), ()) == xq(2) * vertex((1, 1), (), ())
    return True


# ----------------------------------------------------------------------------- vertex table

def cyclic_representatives(max_total: int):
    parts = [p for d in range(max_total + 1) for p in partitions_of(d)]
    seen = set()
    reps = []
    for a in parts:
        for b in parts:
            for c in parts:
                tot = sum(a) + sum(b) + sum(c)
                if tot > max_total:
                    continue
                orbit = {(a, b, c), (b, c, a), (c, a, b)}
                key = min(orbit, key=_order_key)
                if key in seen:
                    continue
                seen.add(key)
                # representative: put the largest partition (by size, then lexicographically) first
                rep = max(orbit, key=lambda t: (tuple(sum(p) for p in t), t))
                reps.append(rep)
    reps.sort(key=lambda t: (sum(map(sum, t)), tuple(-sum(p) for p in t), tuple(tuple(-x for x in p) for p in t)))
    return reps


def _order_key(t):
    return tuple((sum(p), p) for p in t)


def vertex_table(max_total: int = 3) -> str:
    rows = []
    for t in cyclic_representatives(max_total):
        C = vertex(*t)
        trip = ",".join(part_latex(p) for p in t)
        rows.append(rf"$({trip})$ & $\displaystyle {qfrac_latex(C, group_symmetric=False)}$ \\[6pt]")
    body = "\n".join(rows)
    return (r"\begin{tabular}{ll}" "\n" r"\toprule" "\n"
            r"$(\lambda_1,\lambda_2,\lambda_3)$ & $C_{\lambda_1\lambda_2\lambda_3}(q)$\\" "\n"
            r"\midrule" "\n" + body + "\n" r"\bottomrule" "\n" r"\end{tabular}" "\n")


# ----------------------------------------------------------------------------- Z, F, GV

def multicover_reduced(F, gv, beta) -> QFrac:
    """f_beta = F_beta - sum_{k>=2, k|beta} (1/k) sum_g n^g_{beta/k} (-1)^{g-1} [k]^{2g-2}."""
    from math import gcd
    f = F.coeff(beta)
    g0 = 0
    for b in beta:
        g0 = gcd(g0, abs(b))
    for k in range(2, g0 + 1):
        if any(b % k for b in beta):
            continue
        sub = tuple(b // k for b in beta)
        for g, n in gv.get(sub, {}).items():
            sign = -1 if (g - 1) % 2 else 1
            f = f - QFrac.qnum(k) ** (2 * g - 2) * Fraction(sign * n, k)
    return f.cancel()


def _beta_sub(beta, names) -> str:
    if len(beta) == 1:
        return str(beta[0])
    return "(" + ",".join(map(str, beta)) + ")"


def z_block(Z, F, gv, betas) -> str:
    """Three align* blocks: Z_beta; F_beta; y f_beta and the GV numbers."""
    def both(f):
        a, b = qfrac_latex(f), y_form(f)
        return a, (b if b is not None and b != a else None)

    zl, fl, gl = [], [], []
    for beta in betas:
        s = _beta_sub(beta, None)
        a, b = both(Z.coeff(beta))
        zl.append(rf"Z_{{{s}}}&={a}" + (rf"\\&={b}" if b and len(a) + len(b) > 110 else (rf"={b}" if b else "")))
        a, b = both(F.coeff(beta))
        fl.append(rf"F_{{{s}}}&={a}" + (rf"\\&={b}" if b and len(a) + len(b) > 110 else (rf"={b}" if b else "")))
        f = multicover_reduced(F, gv, beta)
        P = (f * QFrac.qnum(1) ** 2).cancel()
        cs = P.to_y_polynomial() if not P.is_zero() else [0]
        ns = gv.get(beta, {})
        nstr = ",\\ ".join(rf"n^{{{g}}}_{{{s}}}={n}" for g, n in sorted(ns.items())) or rf"n^g_{{{s}}}=0\ \text{{for all }}g"
        gl.append(rf"y\,f_{{{s}}}&={y_poly_latex(cs)}&&\Longrightarrow\quad {nstr}")
    sep = "\\\\[3pt]\n"
    return ("\\begin{align*}\n" + sep.join(zl) + "\n\\end{align*}\n"
            "\\begin{align*}\n" + sep.join(fl) + "\n\\end{align*}\n"
            "\\begin{align*}\n" + sep.join(gl) + "\n\\end{align*}\n")


def conifold_terms() -> str:
    from topvertex.examples_geometry import conifold
    from topvertex.partition_function import partition_function, gv_invariants
    g = conifold()
    Z = partition_function(g, 3, weights=[1])
    Zc = Z.substitute({v: {"Q": 1} for v in Z.variables}, ["Q"], [1])
    F = Zc.log()
    gv = gv_invariants(F)
    # check log Z = - sum Q^k / (k [k]^2)
    for k in (1, 2, 3):
        expect = -QFrac.qnum(k) ** (-2) * Fraction(1, k)
        assert F.coeff((k,)) == expect, f"conifold F_{k} mismatch"
    q1, q2, q3, y = QFrac.qnum(1), QFrac.qnum(2), QFrac.qnum(3), _y()
    assert Zc.coeff((1,)) == -1 / y
    assert Zc.coeff((2,)) == QFrac(2) / (q1 ** 2 * q2 ** 2)
    assert Zc.coeff((3,)) == -(y + 6) / (q1 ** 2 * q2 ** 2 * q3 ** 2)
    txt = f"% conifold: framing n = {g.edges[0].n}; checked F_k = -1/(k[k]^2) for k <= 3\n"
    return txt + z_block(Zc, F, gv, [(1,), (2,), (3,)])


def p2_terms() -> str:
    from topvertex.examples_geometry import local_p2
    from topvertex.partition_function import partition_function, gv_invariants
    g = local_p2()
    Z = partition_function(g, 3, weights=[1, 1, 1])
    Zc = Z.substitute({v: {"Q": 1} for v in Z.variables}, ["Q"], [1])
    F = Zc.log()
    gv = gv_invariants(F)
    q1, q2, y = QFrac.qnum(1), QFrac.qnum(2), _y()
    assert Zc.coeff((1,)) == -3 / y
    assert Zc.coeff((2,)) == _ypoly([18, 27, 6]) / (q1 ** 2 * q2 ** 2)
    assert F.coeff((2,)) == (y * 12 + 45) / (y * (y + 4) * 2)
    assert multicover_reduced(F, gv, (2,)) == 6 / y
    sys.path.insert(0, str(ROOT / "tests"))
    import importlib
    oracle = importlib.import_module("data").LOCAL_P2_GV
    for d in (1, 2, 3):
        assert {g: n for g, n in enumerate(oracle[d]) if n} == gv[(d,)], f"P2 degree {d}"
    txt = "% local P^2: package edges " + ", ".join(f"{e.name}(n={e.n},class={e.curve_class})" for e in g.edges) + "\n"
    return txt + z_block(Zc, F, gv, [(1,), (2,), (3,)])


def f0_terms() -> str:
    from topvertex.examples_geometry import local_f0
    from topvertex.partition_function import partition_function, gv_invariants
    g = local_f0()
    # package edges Q0..Q3 = spokes to (1,0),(0,1),(-1,0),(0,-1); Q0,Q2 -> Q_B, Q1,Q3 -> Q_F
    cls = {}
    for e in g.edges:
        i, j = e.segment
        other = j if i == 0 else i
        pt = g.points[other]
        cls[e.name] = {"QB": 1} if pt[1] == 0 else {"QF": 1}
    Z = partition_function(g, 2, weights=[1] * len(g.edges))
    Zc = Z.substitute(cls, ["QB", "QF"], [1, 1])
    F = Zc.log()
    gv = gv_invariants(F)
    q1, q2, y = QFrac.qnum(1), QFrac.qnum(2), _y()
    assert Zc.coeff((1, 0)) == 2 / y == Zc.coeff((0, 1))
    assert Zc.coeff((2, 0)) == (y * 3 + 8) / (q1 ** 2 * q2 ** 2) == Zc.coeff((0, 2))
    assert Zc.coeff((1, 1)) == (y + 1) * 4 / y ** 2
    assert gv[(1, 0)] == {0: -2} and gv[(1, 1)] == {0: -4} and (2, 0) not in gv
    txt = "% local F0: package edges " + ", ".join(f"{e.name}(n={e.n},class={e.curve_class})" for e in g.edges)
    txt += "; B = spokes to (+-1,0), F = spokes to (0,+-1)\n"
    return txt + z_block(Zc, F, gv, [(1, 0), (0, 1), (2, 0), (1, 1), (0, 2)])


def gv_tables() -> str:
    sys.path.insert(0, str(ROOT / "tests"))
    import importlib
    data = importlib.import_module("data")
    P2 = data.LOCAL_P2_GV
    F0 = data.LOCAL_F0_GENUS0
    G = max(len(P2[d]) for d in range(1, 6))  # number of genus columns stored for d <= 5
    out = [r"\begin{tabular}{c|" + "r" * G + "}", r"\toprule",
           "$d$ & " + " & ".join(f"$g={g}$" for g in range(G)) + r"\\", r"\midrule"]
    for d in range(1, 6):
        row = list(P2[d]) + [0] * (G - len(P2[d]))
        out.append(f"${d}$ & " + " & ".join(f"${n}$" for n in row) + r"\\")
    out += [r"\bottomrule", r"\end{tabular}", r"\qquad"]
    out += [r"\begin{tabular}{c|rrrr}", r"\toprule",
            r"$d_B\backslash d_F$ & $0$ & $1$ & $2$ & $3$\\", r"\midrule"]
    for dB in range(0, 4):
        row = []
        for dF in range(0, 4):
            if dB == 0 and dF == 0:
                row.append("--")
            else:
                row.append(f"${F0[(dB, dF)]}$")
        out.append(f"${dB}$ & " + " & ".join(row) + r"\\")
    out += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(out) + "\n"


def main():
    check_hand_values()
    write("vertex_table.tex", vertex_table(3))
    write("gv_tables.tex", gv_tables())
    for name, fn in [("conifold_terms.tex", conifold_terms), ("p2_terms.tex", p2_terms),
                     ("f0_terms.tex", f0_terms)]:
        try:
            write(name, fn())
        except ImportError as exc:  # package module not available yet: keep the placeholder
            print(f"skipping {name}: {exc}", file=sys.stderr)


if __name__ == "__main__":
    main()
